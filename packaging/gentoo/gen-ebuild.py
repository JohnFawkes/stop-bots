#!/usr/bin/env python3
"""Generate the Gentoo ebuild: CRATES from Cargo.lock, LICENSE and
RUST_MIN_VER from `cargo metadata`.

Gentoo's cargo.eclass wants every transitive crate enumerated by name and
version, because the package manager — not cargo — is what fetches them.
This tree has ~400, so the list is generated rather than maintained. So is
the LICENSE line, which Gentoo wants to cover the whole dependency tree,
and RUST_MIN_VER, which is Cargo.toml's `rust-version`.

For a released version, name it:

    python3 packaging/gentoo/gen-ebuild.py 0.0.15

which reads the `v0.0.15` tag rather than the working tree: it exports the
tag to a temporary directory and runs `cargo metadata --locked` there. The
ebuild builds that tag's source archive, so its CRATES must be that tag's
lock file and its LICENSE that tag's dependencies; the working tree has
usually moved on by the time the release is out. `packaging/bump.py` runs
this for you.

With no argument it uses the working tree, for trying an unreleased tree
in a local overlay.

`cargo metadata` needs the registry index, so this reads from the network
unless cargo has the tree cached already; it writes nothing but the ebuild.

## Why CRATES still lists the dev-only crates

About 60 of the crates in Cargo.lock are reachable only through
`[dev-dependencies]`: resvg, gif and what they pull in for the README's
animated tour, plus the test harness crates. They are never compiled into
the binary, and this script can tell which they are (`normal_crates`).
They stay in CRATES anyway, because cargo cannot build without them:
cargo.eclass replaces crates.io with a directory of exactly the crates
listed, and cargo resolves a package's dev-dependencies even for `cargo
build`. With them removed from such a directory, even `cargo check
--offline` stops at `no matching package named assert_cmd found`. That was
tried, not assumed. They are also what `src_test` runs with.

Where the distinction does matter is LICENSE, which describes what is
installed: it is computed from the crates compiled into the binary (normal
and build dependencies, for every target) and not from the dev-only ones.
"""

import io
import json
import pathlib
import re
import subprocess
import sys
import tarfile
import tempfile
import textwrap

ROOT = pathlib.Path(__file__).resolve().parents[2]

# SPDX identifier -> Gentoo licence name, from ::gentoo's
# metadata/license-mapping.conf (the table pycargoebuild uses too). Only the
# identifiers this dependency tree has needed so far: an identifier that is
# not here stops the script, rather than being guessed at. Add it from that
# file, `[spdx-to-ebuild]` section.
SPDX_TO_GENTOO = {
    "0BSD": "0BSD",
    "AGPL-3.0-only": "AGPL-3",
    "AGPL-3.0-or-later": "AGPL-3+",
    "Apache-2.0": "Apache-2.0",
    "Apache-2.0 WITH LLVM-exception": "Apache-2.0-with-LLVM-exceptions",
    "BSD-2-Clause": "BSD-2",
    "BSD-3-Clause": "BSD",
    "BSL-1.0": "Boost-1.0",
    "CC0-1.0": "CC0-1.0",
    "CDLA-Permissive-2.0": "CDLA-Permissive-2.0",
    "ISC": "ISC",
    "LGPL-2.1-or-later": "LGPL-2.1+",
    "MIT": "MIT",
    "MIT-0": "MIT-0",
    "MPL-2.0": "MPL-2.0",
    "Unicode-3.0": "Unicode-3.0",
    "Unicode-DFS-2016": "Unicode-DFS-2016",
    "Unlicense": "Unlicense",
    "WTFPL": "WTFPL-2",
    "Zlib": "ZLIB",
}

TEMPLATE = '''# Copyright 2026 Marko Ivankovic
# Distributed under the terms of the GNU Affero General Public License v3

EAPI=8

# Generated by packaging/gentoo/gen-ebuild.py: CRATES from Cargo.lock,
# LICENSE and RUST_MIN_VER from `cargo metadata`. Do not edit by hand —
# regenerate after a version bump.
#
# Every crate in Cargo.lock, the dev-only ones included: cargo resolves
# dev-dependencies even to build, so without them the vendored build does
# not start, and src_test needs them anyway. See gen-ebuild.py.
CRATES="
{crates}
"

# Cargo.toml's `rust-version`, which CI's MSRV job builds with. Set before
# `inherit`, as rust.eclass requires.
RUST_MIN_VER="{rust_min_ver}"

inherit cargo

DESCRIPTION="TUI and CLI to stop bad bots in NGINX, Apache or Traefik and the firewall"
HOMEPAGE="https://github.com/ivankovic/stop-bots"
SRC_URI="
	https://github.com/ivankovic/stop-bots/archive/v${{PV}}.tar.gz -> ${{P}}.tar.gz
	${{CARGO_CRATE_URIS}}
"

# This package's own licence, then those of the crates compiled into it:
# each crate's SPDX `license`, mapped as ::gentoo's license-mapping.conf
# does, with an any-of group dropped where one of its licences is already
# required. The dev-only crates are not counted; nothing of theirs is
# installed.
LICENSE="{license}"
# Dependent crate licenses
LICENSE+="
{crate_licenses}
"

SLOT="0"
KEYWORDS="~amd64"

# rusqlite is built with its `bundled` feature, so SQLite is compiled from
# vendored C sources here rather than linked against dev-db/sqlite. That is a
# toolchain requirement, not a runtime dependency.
DEPEND=""
RDEPEND="${{DEPEND}}"

# The container suite needs Docker and NET_ADMIN; src_test must not.
src_test() {{
	cargo_src_test
}}
'''


def crates_from_lock(text: str) -> list[str]:
    out = []
    for block in text.split("[[package]]")[1:]:
        name = re.search(r'^name = "(.+)"', block, re.M)
        version = re.search(r'^version = "(.+)"', block, re.M)
        # A package with no `source` is this workspace's own crate, which the
        # eclass must not try to fetch from crates.io.
        source = re.search(r'^source = "(.+)"', block, re.M)
        if name and version and source:
            out.append(f"{name.group(1)}@{version.group(1)}")
    return sorted(out)


def cargo_metadata(tree: pathlib.Path) -> dict:
    """`cargo metadata` for the tree, held to its Cargo.lock."""
    result = subprocess.run(
        [
            "cargo", "metadata", "--locked", "--format-version", "1",
            "--manifest-path", str(tree / "Cargo.toml"),
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"cargo metadata failed in {tree}:\n{result.stderr}")
    return json.loads(result.stdout)


def normal_crates(meta: dict) -> tuple[dict, list[dict]]:
    """This package, and every crate built into its binary: everything
    reachable from it through normal and build dependencies, for every
    target. The dev-dependencies are left out, and so is everything only
    they bring in. Below the root package, the resolve has no dev edges."""
    nodes = {node["id"]: node for node in meta["resolve"]["nodes"]}
    packages = {package["id"]: package for package in meta["packages"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            if {kind["kind"] for kind in dep["dep_kinds"]} != {"dev"}:
                stack.append(dep["pkg"])
    seen.discard(root)
    return packages[root], [packages[i] for i in sorted(seen)]


# --- SPDX expression -> Gentoo LICENSE ---------------------------------------
#
# A parsed expression is a licence name (str), or ("all", [...]) or
# ("any", [...]). AND binds tighter than OR, as SPDX says; the legacy `/`
# separator that older crates still use is OR.


def spdx_tokens(expression: str) -> list[str]:
    tokens = re.findall(r"\(|\)|[^\s()]+", expression.replace("/", " OR "))
    # `X WITH Y` is one licence, and is mapped as one.
    out = []
    i = 0
    while i < len(tokens):
        if i + 2 < len(tokens) and tokens[i + 1] == "WITH":
            out.append(f"{tokens[i]} WITH {tokens[i + 2]}")
            i += 3
        else:
            out.append(tokens[i])
            i += 1
    return out


def parse_spdx(expression: str, crate: str):
    tokens = spdx_tokens(expression)
    pos = 0

    def peek():
        return tokens[pos] if pos < len(tokens) else None

    def take():
        nonlocal pos
        pos += 1
        return tokens[pos - 1]

    def term():
        token = take()
        if token == "(":
            inner = any_of()
            if take() != ")":
                raise SystemExit(f"{crate}: unbalanced licence {expression!r}")
            return inner
        if token in ("AND", "OR", ")"):
            raise SystemExit(f"{crate}: cannot parse licence {expression!r}")
        if token not in SPDX_TO_GENTOO:
            raise SystemExit(
                f"{crate}: licence {token!r} has no Gentoo name here. Add it to "
                "SPDX_TO_GENTOO in gen-ebuild.py from ::gentoo's "
                "metadata/license-mapping.conf."
            )
        return SPDX_TO_GENTOO[token]

    def all_of():
        parts = [term()]
        while peek() == "AND":
            take()
            parts.append(term())
        return parts[0] if len(parts) == 1 else ("all", parts)

    def any_of():
        parts = [all_of()]
        while peek() == "OR":
            take()
            parts.append(all_of())
        return parts[0] if len(parts) == 1 else ("any", parts)

    parsed = any_of()
    if peek() is not None:
        raise SystemExit(f"{crate}: cannot parse licence {expression!r}")
    return parsed


def requirements(parsed) -> list:
    """Flatten a top-level all-of into its separate requirements."""
    if isinstance(parsed, tuple) and parsed[0] == "all":
        return [r for part in parsed[1] for r in requirements(part)]
    return [parsed]


def render(parsed) -> str:
    if isinstance(parsed, str):
        return parsed
    kind, parts = parsed
    inner = " ".join(render(p) for p in sorted(parts, key=render))
    return f"|| ( {inner} )" if kind == "any" else f"( {inner} )"


def satisfied(parsed, required: set[str]) -> bool:
    """Whether accepting `required` alone already accepts this term."""
    if isinstance(parsed, str):
        return parsed in required
    kind, parts = parsed
    test = any if kind == "any" else all
    return test(satisfied(p, required) for p in parts)


def dependency_licence(crates: list[dict]) -> list[str]:
    """The LICENSE terms the crates need between them, simplest first.

    Every licence some crate requires outright is listed once. An any-of
    group is dropped when one of its alternatives is already listed — that
    one licence satisfies it — and otherwise kept, once.
    """
    required: set[str] = set()
    groups = []
    for crate in crates:
        label = f"{crate['name']}@{crate['version']}"
        if not crate.get("license"):
            raise SystemExit(
                f"{label} declares no SPDX `license` (license-file only?); "
                "read its licence and add it to the ebuild by hand."
            )
        for req in requirements(parse_spdx(crate["license"], label)):
            if isinstance(req, str):
                required.add(req)
            else:
                groups.append(req)
    kept = {}
    for group in groups:
        if not satisfied(group, required):
            kept[render(group)] = group
    return sorted(required) + sorted(kept)


def wrap(terms: list[str]) -> str:
    """Tab-indented lines of at most ~72 columns, as pycargoebuild writes."""
    return "\n".join(
        "\t" + line
        for line in textwrap.wrap(
            " ".join(terms), width=72, break_long_words=False, break_on_hyphens=False
        )
    )


def export_tag(version: str, dest: pathlib.Path) -> None:
    """The tree at `v<version>`, as `git archive` has it, into dest."""
    tag = f"v{version}"
    result = subprocess.run(
        ["git", "-C", str(ROOT), "archive", "--format=tar", tag],
        capture_output=True,
    )
    if result.returncode != 0:
        raise SystemExit(
            f"cannot export {tag}: {result.stderr.decode().strip()}\n"
            "(is the tag fetched? `git fetch --tags`)"
        )
    with tarfile.open(fileobj=io.BytesIO(result.stdout)) as archive:
        archive.extractall(dest, filter="data")


def write_ebuild(version: str, tree: pathlib.Path) -> pathlib.Path:
    """Write stop-bots-<version>.ebuild from the source tree at `tree`."""
    crates = crates_from_lock((tree / "Cargo.lock").read_text())
    meta = cargo_metadata(tree)
    root, compiled = normal_crates(meta)

    rust_version = root.get("rust_version")
    if not rust_version:
        raise SystemExit("Cargo.toml has no rust-version")
    # Cargo writes `1.88`; rust.eclass compares against slots like 1.88.0.
    rust_min_ver = ".".join((rust_version.split(".") + ["0", "0"])[:3])

    own = render(parse_spdx(root["license"], root["name"]))
    body = TEMPLATE.format(
        crates="\n".join(f"\t{c}" for c in crates),
        rust_min_ver=rust_min_ver,
        license=own,
        crate_licenses=wrap(dependency_licence(compiled)),
    )

    dest = pathlib.Path(__file__).parent / f"stop-bots-{version}.ebuild"
    dest.write_text(body)
    print(
        f"wrote {dest.relative_to(ROOT)} ({len(crates)} crates, "
        f"licences from the {len(compiled)} compiled in)"
    )
    return dest


def write_ebuild_at_tag(version: str) -> pathlib.Path:
    with tempfile.TemporaryDirectory(prefix="stop-bots-ebuild-") as tmp:
        export_tag(version, pathlib.Path(tmp))
        return write_ebuild(version, pathlib.Path(tmp))


def main(argv: list[str]) -> int:
    if len(argv) > 2:
        print(f"usage: {argv[0]} [version]", file=sys.stderr)
        return 2

    if len(argv) == 2:
        write_ebuild_at_tag(argv[1].removeprefix("v"))
        return 0

    if not (ROOT / "Cargo.lock").exists():
        print(f"no Cargo.lock at {ROOT}", file=sys.stderr)
        return 1
    version = re.search(
        r'^version = "(.+)"', (ROOT / "Cargo.toml").read_text(), re.M
    ).group(1)
    write_ebuild(version, ROOT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
